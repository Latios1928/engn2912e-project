#!/usr/bin/env python3
"""Write lib.spice: the d_cosim instance of a vlnggen-built Verilog module,
with bridges to the analog nets of the same names.

Adapted from CAD7/instantiate.py of engn1600-team1:
  https://github.com/mgyee/engn1600-team1
Things it has to get right:
  - Port order. d_cosim takes the ports in the order of
    <module>_obj_dir/inputs.h and outputs.h, which is not the order in the
    Verilog source. Both headers are read here; never write this line by hand.
  - Bit order. Within a bus, bits go MSB first (checked in a smoke test).
  - Brackets. XSPICE vectors are written [ a b c ], so a node called w[5]
    inside one is a parse error. Bridges therefore use flat nodes (a_w_5) and
    a 0 V source links each one to the bracketed net xschem writes (w[5]).
    Single-bit ports keep their own name on the analog side.
  - Width. ngspice's shim reads port bits with (1 << i), so a port must be
    at most 31 bits wide. Split wider buses into ports named <bus>_at<N>:
    bit i of <bus>_at<N> becomes the analog net <bus>[N + i]. (Not <bus>__<N>:
    Verilator mangles a double underscore to ___05F.)

Usage:
  instantiate.py --obj-dir snn_digital_obj_dir --module snn_digital \
                 --so /abs/path/snn_digital.so [--vdd 3.3] > lib.spice
"""

import argparse
import re
from pathlib import Path

VL_DATA_RE = re.compile(r"VL_DATA\((\w*),(\w+),(\d+),(\d+)")
SPLIT_RE = re.compile(r"^(\w+?)_at(\d+)$")


def ports(header):
    """[(name, [bit, ...] or None)] in header order; bits MSB first."""
    out = []
    for size, name, msb, lsb in VL_DATA_RE.findall(header.read_text()):
        msb, lsb = int(msb), int(lsb)
        if size == "W" or msb > 30:
            raise SystemExit(f"instantiate.py: port {name}[{msb}:{lsb}] is too wide for d_cosim (max 31 bits); "
                             "split it into <bus>_at<N> ports")
        if msb == lsb == 0:
            out.append((name, None))
        else:
            step = -1 if msb > lsb else 1
            out.append((name, list(range(msb, lsb + step, step))))
    return out


def expand(plist):
    """[(digital node, bridge node, analog net)] for every bit."""
    bits = []
    for name, idx in plist:
        if idx is None:
            bits.append((f"d_{name}", name, name))
        else:
            m = SPLIT_RE.match(name)
            bus, base = (m.group(1), int(m.group(2))) if m else (name, 0)
            for i in idx:
                bits.append((f"d_{bus}_{base + i}", f"a_{bus}_{base + i}", f"{bus}[{base + i}]"))
    return bits


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--obj-dir", type=Path, required=True)
    ap.add_argument("--module", required=True)
    ap.add_argument("--so", required=True, help="absolute path of the .so")
    ap.add_argument("--vdd", type=float, default=3.3)
    args = ap.parse_args()

    if (args.obj_dir / "inouts.h").exists() and VL_DATA_RE.search((args.obj_dir / "inouts.h").read_text()):
        raise SystemExit("instantiate.py: inout ports are not supported")

    ins = expand(ports(args.obj_dir / "inputs.h"))
    outs = expand(ports(args.obj_dir / "outputs.h"))
    m = args.module
    vth = args.vdd / 2

    def vec(nodes):
        return "[ " + " ".join(nodes) + " ]"

    links = [f"Vlk_{b} {a} {b} 0" for _, b, a in ins if b != a]
    links += [f"Vlk_{b} {b} {a} 0" for _, b, a in outs if b != a]
    nl = "\n"

    print(f"""\
* {m}: d_cosim model and bridges. Generated by instantiate.py; do not edit.
* Port order from {args.obj_dir}/inputs.h and outputs.h.

.model {m}_adc adc_bridge(in_low={vth - 0.01:.3f} in_high={vth + 0.01:.3f})
.model {m}_dac dac_bridge(out_low=0 out_high={args.vdd} t_rise=10n t_fall=10n)
.model {m} d_cosim simulation="{args.so}" delay=10p

* Analog -> digital
a{m}_adc {vec(b for _, b, _ in ins)}
+ {vec(d for d, _, _ in ins)} {m}_adc

a{m} {vec(d for d, _, _ in ins)}
+ {vec(d for d, _, _ in outs)} null {m}

* Digital -> analog
a{m}_dac {vec(d for d, _, _ in outs)}
+ {vec(b for _, b, _ in outs)} {m}_dac

* Links from the flat bridge nodes to bracketed nets
{nl.join(links)}""")

if __name__ == "__main__":
    main()
