"""Write xor_tb.sch: the 2-2-1 snn_analog in pure ngspice, set up for the 4 XOR input cases.

    python3 analog/testbenches/xor/gen_xor_tb.py

Run it again after analog/snn/gen_snn_analog.py changes the symbol's pins. Weights are the signed
parameters c0..c7 (-7..+7, word k of mock/snn_analog.v), turned into sign-magnitude bits.
"""

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SYM = ROOT / "analog/snn/snn_analog.sym"

# Default weights: XOR with hidden 0 = OR and hidden 1 = AND (inhibitory onto the output)
C = {"c0": 7, "c1": 7, "c2": 7, "c3": 7, "c4": 2, "c5": 2, "c6": 1, "c7": -7}

PARAMS = """.param vdd=3.3 iref=14.42n
.param p_vthr=2.70 p_vtau=0.5096 p_vtau_i=0.5096
.param p_vthr_in=2.4 p_vtau_in=0.695 p_vthr_hid=2.5 p_vtau_hid=0.655
.param p_vlk=0.48 p_vamp_bias=0.535 p_vip=0.573 p_vna=1.93 p_vkup=2.35 p_vk=1.22 p_vkdn=0.588 p_vt=1.66
* Signed weights -7..+7, word k: 0, 1 pulse -> input; 2 + 2j + i input i -> hidden j; 6 + j hidden j -> output
.param {cs}
.param ina=1 inb=1 tpw=10u tsp=200u t0=100u tstop=4.1m
.csparam tstop_c=\\{{tstop\\}}"""

SOURCES = """Vdd VDD 0 \\{vdd\\}
Vss VSS 0 0
* DAC unit current: Iref into a diode-connected unit current source (w[0] = 15 nA)
Iref VDD Vb \\{iref\\}
XMref Vb Vb 0 0 nfet_03v3 L=8u W=1u nf=1
* VT_* are source-gate voltages of the DPI tau pFET (VT = VDD - p_vtau)
Vthr Vthr 0 \\{p_vthr\\}
Vtau VDD VT_dpi \\{p_vtau\\}
Vtau_i VDD VT_inh \\{p_vtau_i\\}
Vthr_in Vthr_in 0 \\{p_vthr_in\\}
Vtau_in VDD VT_in \\{p_vtau_in\\}
Vthr_hid Vthr_hid 0 \\{p_vthr_hid\\}
Vtau_hid VDD VT_hid \\{p_vtau_hid\\}
VNA VNA VSS \\{p_vna\\}
Vlk Vlk VSS \\{p_vlk\\}
VK VK VSS \\{p_vk\\}
VIp VIp VSS \\{p_vip\\}
VKup VKup VSS \\{p_vkup\\}
VKdn VKdn VSS \\{p_vkdn\\}
Vamp_bias Vamp_bias VSS \\{p_vamp_bias\\}
VT VT VSS \\{p_vt\\}"""

CONTROL = """.ic {ic}
.options method=gear

.control
  save {sv}
  set wr_singlescale
  set wr_vecnames
  * Max step 0.1u: at 0.5u a relay spike edge sometimes kicked a neuron into a false spike
  tran 0.1u $&tstop_c 0 0.1u
  meas tran vmax_out max v(x1.VMEM_4)
  echo RES vmax_out=$&vmax_out
  wrdata xor_tb.txt {sv}
  if $?batchmode = 0
    plot v(x1.VMEM_4) v(sp4)+4 v(sp2)*0.3+8 v(sp3)*0.3+9.5 v(sp0)*0.3+11 v(sp1)*0.3+12.5 title 'Output membrane, output spike; hidden OR, AND; inputs A, B (offset)' ylabel 'V'
  end
.endc"""


def main():
    pins = {}
    for m in re.finditer(r"^B 5 (\S+) (\S+) (\S+) (\S+) \{name=(\S+) dir=", SYM.read_text(), re.M):
        x1, y1, x2, y2 = map(float, m.groups()[:4])
        pins[m.group(5)] = ((x1 + x2) / 2, (y1 + y2) / 2)
    lines = ["v {xschem version=3.4.8RC file_version=1.3}", "G {}", "K {}", "V {}", "S {}", "F {}", "E {}"]
    lines.append("T {xor_tb: the 2-2-1 snn_analog (pure ngspice, no Verilog), weights c0..c7 signed (-7..+7).\n"
                 "pulse[0] = A (ina), pulse[1] = B (inb): 10 us pulses every tsp from t0. Membranes start at 0 V.\n"
                 "run_xor.py counts the spikes of every neuron in the wrdata file. Generated by gen_xor_tb.py.\n"
                 "Default weights: XOR with hidden 0 = OR (+1 to the output) and hidden 1 = AND (+2 from each input, -7 to the output).}"
                 " -900 -700 0 0 0.3 0.3 {}")
    x0, y0 = 300, -200
    lines.append(f"C {{snn_analog.sym}} {x0} {y0} 0 0 {{name=x1}}")
    for i, (p, (px, py)) in enumerate(pins.items()):
        lines.append(f"C {{lab_pin.sym}} {x0 + px:g} {y0 + py:g} 0 {1 if px > 0 else 0} "
                     f"{{name=l{i + 1} sig_type=std_logic lab={p}}}")
    lines.append('C {code_shown.sym} -900 -350 0 0 {name=MODELS only_toplevel=true\nformat="tcleval( @value )"\n'
                 'value="\n.include $::180MCU_MODELS/design.ngspice\n.lib $::180MCU_MODELS/sm141064.ngspice typical\n'
                 '.lib $::180MCU_MODELS/sm141064.ngspice mimcap_typical\n"}')
    body = [PARAMS.format(cs=" ".join(f"{k}={v}" for k, v in C.items())), SOURCES]
    for k in range(8):
        c = f"c{k}"
        for b in range(3):
            body.append(f"Vw{4 * k + b} w[{4 * k + b}] 0 \\{{vdd*(floor(abs({c})/{2 ** b})-2*floor(abs({c})/{2 ** (b + 1)}))\\}}")
        body.append(f"Vw{4 * k + 3} w[{4 * k + 3}] 0 \\{{{c}<0 ? vdd : 0\\}}")
    body += ["Vp0 pulse[0] 0 pulse(0 \\{vdd*ina\\} \\{t0\\} 10n 10n \\{tpw\\} \\{tsp\\})",
             "Vp1 pulse[1] 0 pulse(0 \\{vdd*inb\\} \\{t0\\} 10n 10n \\{tpw\\} \\{tsp\\})",
             "* spike[n] copied to sp<n> (no load) for wrdata"]
    body += [f"Esp{n} sp{n} 0 spike[{n}] 0 1" for n in range(5)]
    sv = " ".join([f"v(sp{n})" for n in range(5)] + [f"v(x1.VMEM_{n})" for n in range(5)])
    ic = " ".join([f"v(x1.VMEM_{n})=0" for n in range(5)] + [f"v(spike[{n}])=0" for n in range(5)])
    body.append(CONTROL.format(sv=sv, ic=ic))
    lines.append('C {code_shown.sym} -900 -230 0 0 {name=TRAN_SIM only_toplevel=false\nvalue="' + "\n".join(body) + '\n"}')
    (HERE / "xor_tb.sch").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
