"""
Well-bias audit for a GF180 layout: every isolated well must be tapped, tied to the right net, and
reverse-biased.

    LVSDB=<file.lvsdb> klayout -b -r well_bias_check.py -rd gds=SNN.gds -rd out=SNN_well_bias.md

Checks, per well (from the drawn layers of the flattened layout):
  * LVPWELL islands (isolated P-wells inside DNWELL): P+ taps inside the island, the net each tap
    connects to (probed in the LVS database, i.e. the extracted connectivity), the DNWELL that holds
    the island, and the largest distance from any N+ diffusion in the island to the nearest tap in
    the SAME island (DRC rule DF.14 accepts any P+ tap, even one in another well, so it cannot
    check this).
  * DNWELL regions: N+ taps (outside the LVPWELLs) and their net; a DNWELL must be on the highest
    supply (VDD) so that both its junctions (to the substrate and to its LVPWELLs) stay reverse-biased.
  * NWELL regions: N+ taps and their net (VDD expected).
  * P substrate: P+ taps outside all wells and their net (VSS expected).
The report lists the nets; whether a body net is safe is judged in the report's summary (body net
<= every source/drain on it, and below the DNWELL).
"""
import os
import pya

GDS = globals().get("gds", "SNN.gds")
OUT = globals().get("out", "")
TAP_MAX = 20.0          # um, DF.14_LV distance, applied per island here

ly = pya.Layout()
ly.read(GDS)
top = ly.top_cell()
dbu = ly.dbu


def R(l, d):
    li = ly.find_layer(l, d)
    return pya.Region(top.begin_shapes_rec(li)).merged() if li is not None else pya.Region()


dnw, lpw, nw = R(12, 0), R(204, 0), R(21, 0)
comp, poly, pp, np_, cont = R(22, 0), R(30, 0), R(31, 0), R(32, 0), R(33, 0)
m1 = R(34, 0)
pcomp = (comp & pp) - poly           # P+ diffusion not under a gate
ncomp_all = comp & np_
ptap_cand = pcomp.interacting(cont)
ntap_cand = (ncomp_all - poly).interacting(cont)

# ------------------------------------------------------------------ nets from the LVS database
lvs = pya.LayoutVsSchematic()
lvs.read(os.environ["LVSDB"])
ily = lvs.internal_layout()
src_m1 = m1
m1_idx = None
for i in lvs.layer_indexes():
    r = lvs.layer_by_index(i).merged()
    if not r.is_empty() and (r ^ src_m1).area() <= 0.002 * src_m1.area():
        m1_idx = i
        break
assert m1_idx is not None, "Metal1 not found in the LVS database"
m1_layer = lvs.layer_by_index(m1_idx)
xref = lvs.xref()
sch_name = {}
for cp in xref.each_circuit_pair():
    for np2 in xref.each_net_pair(cp):
        if np2.first() and np2.second():
            sch_name[(cp.first().name if cp.first() else "", np2.first().expanded_name())] = np2.second().name


def net_at(poly):
    """Net of the Metal1 over a tap (probed at a contact inside the tap polygon itself; a ring tap's
    bounding box would also hold unrelated contacts)."""
    cs = (cont & pya.Region(poly)).each()
    for c in cs:
        p = c.bbox().center()
        n = lvs.probe_net(m1_layer, pya.DPoint(p.x * dbu, p.y * dbu))
        if n:
            circ = n.circuit().name
            return "%s/%s" % (circ, sch_name.get((circ, n.expanded_name()), n.expanded_name()))
    return "(no net)"


def nets_of(region):
    out = {}
    for t in region.each():
        n = net_at(t)
        out[n] = out.get(n, 0) + 1
    return out


def bdist(a, b):
    """distance between two boxes (0 if they touch)"""
    dx = max(0, max(a.left, b.left) - min(a.right, b.right))
    dy = max(0, max(a.bottom, b.bottom) - min(a.top, b.top))
    return (dx * dx + dy * dy) ** 0.5 * dbu


lines = ["# Well-bias audit: %s" % os.path.basename(GDS), "",
         "Generated by `well_bias_check.py`. Nets are probed in the LVS database "
         "(`%s`): `<circuit>/<net>` with the schematic net name." % os.path.basename(os.environ["LVSDB"]), ""]
issues = []

# ------------------------------------------------------------------ LVPWELL islands
lines += ["## Isolated P-wells (LVPWELL)", "",
          "| # | island (um) | in DNWELL | P+ taps | tap net(s) | N+ diffusions | farthest N+ from a tap in the island (um) |",
          "|---|---|---|---|---|---|---|"]
dn_polys = list(dnw.each())
for k, isl in enumerate(sorted(lpw.each(), key=lambda p: (p.bbox().bottom, p.bbox().left))):
    ri = pya.Region(isl)
    taps = ptap_cand & ri
    dev = (ncomp_all & ri)
    dn_in = [j for j, d in enumerate(dn_polys) if pya.Region(d).covering(ri).count() or not (pya.Region(d) & ri).is_empty()]
    nets = nets_of(taps)
    worst = 0.0
    tb = [t.bbox() for t in taps.each()]
    for dpoly in dev.each():
        b = dpoly.bbox()
        dmin = min((bdist(b, t) for t in tb), default=float("inf"))
        worst = max(worst, dmin)
    bb = isl.bbox().to_dtype(dbu)
    lines.append("| %d | (%.1f, %.1f)-(%.1f, %.1f) | %s | %d | %s | %d | %s |" % (
        k, bb.left, bb.bottom, bb.right, bb.top, ",".join("DN%d" % j for j in dn_in) or "**none**",
        taps.count(), ", ".join("%s x%d" % kv for kv in sorted(nets.items())) or "**none**", dev.count(),
        "%.2f" % worst if tb else "**no tap**"))
    if not tb:
        issues.append("LVPWELL #%d has no P+ tap (floating well)" % k)
    if len(nets) > 1:
        issues.append("LVPWELL #%d is tapped to more than one net: %s" % (k, list(nets)))
    if worst > TAP_MAX:
        issues.append("LVPWELL #%d: N+ diffusion %.1f um from the nearest tap in the island (> %g um)" % (k, worst, TAP_MAX))
    if not dn_in:
        issues.append("LVPWELL #%d is not inside a DNWELL" % k)
lines.append("")

# ------------------------------------------------------------------ DNWELL
lines += ["## Deep N-wells (DNWELL)", "", "| # | region (um) | LVPWELL islands inside | N+ taps (outside LVPWELL) | tap net(s) |", "|---|---|---|---|---|"]
for j, d in enumerate(dn_polys):
    rd = pya.Region(d)
    taps = (ntap_cand & rd) - lpw
    nets = nets_of(taps)
    nisl = sum(1 for isl in lpw.each() if not (pya.Region(isl) & rd).is_empty())
    bb = d.bbox().to_dtype(dbu)
    lines.append("| DN%d | (%.1f, %.1f)-(%.1f, %.1f) | %d | %d | %s |" % (
        j, bb.left, bb.bottom, bb.right, bb.top, nisl, taps.count(), ", ".join("%s x%d" % kv for kv in sorted(nets.items())) or "**none**"))
    if taps.is_empty():
        issues.append("DNWELL DN%d has no N+ tap (floating)" % j)
    elif any(not n.endswith("/VDD") for n in nets):
        issues.append("DNWELL DN%d tapped to %s (expected VDD)" % (j, list(nets)))
lines.append("")

# ------------------------------------------------------------------ NWELL
lines += ["## N-wells (NWELL)", "", "| # | region (um) | in DNWELL | N+ taps | tap net(s) |", "|---|---|---|---|---|"]
for j, w in enumerate(nw.each()):
    rw = pya.Region(w)
    taps = ntap_cand & rw
    nets = nets_of(taps)
    bb = w.bbox().to_dtype(dbu)
    indn = not (rw & dnw).is_empty()
    lines.append("| NW%d | (%.1f, %.1f)-(%.1f, %.1f) | %s | %d | %s |" % (
        j, bb.left, bb.bottom, bb.right, bb.top, "yes" if indn else "no", taps.count(),
        ", ".join("%s x%d" % kv for kv in sorted(nets.items())) or ("(via DNWELL)" if indn else "**none**")))
    if taps.is_empty() and not indn:
        issues.append("NWELL NW%d has no N+ tap" % j)
    elif any(not n.endswith("/VDD") for n in nets):
        issues.append("NWELL NW%d tapped to %s (expected VDD)" % (j, list(nets)))
lines.append("")

# ------------------------------------------------------------------ substrate
subtaps = ptap_cand - lpw - nw - dnw
nets = nets_of(subtaps)
lines += ["## P substrate", "", "P+ taps outside all wells: %d, nets: %s" % (subtaps.count(), ", ".join("%s x%d" % kv for kv in sorted(nets.items()))), ""]
bad = [n for n in nets if not (n.endswith("/VSS") or n.endswith("/GND"))]
if bad:
    issues.append("substrate taps on %s (expected VSS/GND)" % bad)

lines += ["## Junction polarity (this project's body nets)", "",
          "Every junction must stay reverse-biased (or at zero bias) in operation:", "",
          "| junction | n side | p side | why it is reverse-biased |", "|---|---|---|---|",
          "| DNWELL / P substrate | VDD | VSS | VDD is the highest, VSS the lowest supply |",
          "| DNWELL / LVPWELL | VDD | VSS, Isum_k, DAC branch nodes | every LVPWELL net stays below VDD (Isum_k sits at about 2.0-2.6 V, the branch nodes between 0 V and Isum) |",
          "| N+ S/D / LVPWELL on VSS | S/D of the NMOS (current sources, Men, neuron NMOS) | VSS | VSS is the lowest node |",
          "| N+ S/D / LVPWELL on Isum_k (DPI M1, M2) | sources: Isum_k; drains: VDD, net1 | Isum_k | body = source; both drains are above Isum_k |",
          "| N+ S/D / LVPWELL on a DAC branch node (weight switches) | source: branch node; drain: X | branch node | body = source; the DAC current flows from X into the branch node, so X >= branch node |",
          "| NWELL / P substrate (DAC_signed inverter, bias cell) | VDD | VSS | as above |",
          "| P+ S/D / NWELL or DNWELL (PMOS) | VDD | PMOS S/D | every PMOS S/D is at or below VDD |",
          "", "Dummy transistors have every terminal on their well's net (zero bias).", ""]
lines += ["## Issues found", ""] + (["- " + i for i in issues] if issues else ["None."]) + [""]
txt = "\n".join(lines) + "\n"
if OUT:
    open(OUT, "w").write(txt)
print(txt)
