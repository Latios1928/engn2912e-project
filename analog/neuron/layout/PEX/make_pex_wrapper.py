"""Write <cell>_pex_wrapper.spice: the extracted <cell> with its symbol's pin order.

    python3 make_pex_wrapper.py neuron_sized

Magic (RC_extract.sh) writes <cell>_pex.spice with subcircuit <cell>_flat and
its pins in whatever order Magic found them. Testbenches connect subcircuit
pins by position, in the order of the pins in analog/neuron/<cell>.sym. This
script reads both, checks that they have the same pins, and writes a wrapper
subcircuit <cell>_pex with the symbol's order, so a testbench can swap
"<cell>" for "<cell>_pex" and nothing else.

Run it inside the container (extract.sh does), so that the .include path in
the wrapper is the container path that ngspice sees.
"""

import datetime
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent          # analog/neuron/layout/PEX

# Layout pins that the symbol does not have because the schematic uses a global
# net for them. xschem netlists the GND label as ".GLOBAL GND", and ngspice treats
# a node named gnd as ground, so these connect to GND inside the wrapper.
# VSUBS is the name Magic gives the substrate when it has no label.
GLOBAL_PINS = {"gnd": "GND", "vsubs": "GND"}
SYMDIR = HERE.parents[1]                        # analog/neuron


def subckt_pins(spice: Path, name: str) -> list[str]:
    """Pins of .subckt <name> in a SPICE file (continuation lines joined)."""
    text = re.sub(r"\n\+", " ", spice.read_text())
    for line in text.splitlines():
        t = line.split()
        if len(t) >= 2 and t[0].lower() == ".subckt" and t[1].lower() == name.lower():
            return [p for p in t[2:] if "=" not in p]
    raise SystemExit(f"error: no .subckt {name} in {spice}")


def symbol_pins(sym: Path) -> list[str]:
    """Pin names of an xschem symbol in file order, buses expanded (w[3:0] -> w[3] ... w[0])."""
    pins = []
    for line in sym.read_text().splitlines():
        if line.startswith("B 5 "):
            m = re.search(r"\bname=([^\s}]+)", line)
            if not m:
                continue
            bus = re.fullmatch(r"(.+)\[(\d+):(\d+)\]", m.group(1))
            if bus:
                base, hi, lo = bus.group(1), int(bus.group(2)), int(bus.group(3))
                step = -1 if hi >= lo else 1
                pins += [f"{base}[{i}]" for i in range(hi, lo + step, step)]
            else:
                pins.append(m.group(1))
    if "sim_pinnumber" in sym.read_text():
        raise SystemExit(f"error: {sym} sets sim_pinnumber; pin order is not the file order, "
                         "write the wrapper by hand")
    return pins


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    cell = sys.argv[1]
    pex = HERE / f"{cell}_pex.spice"
    sym = SYMDIR / f"{cell}.sym"
    gds = HERE / f"{cell}.gds"
    for f in (pex, sym, gds):
        if not f.exists():
            raise SystemExit(f"error: {f} not found")

    flat = subckt_pins(pex, f"{cell}_flat")
    want = symbol_pins(sym)
    by_lower = {p.lower(): p for p in flat}
    missing = [p for p in want if p.lower() not in by_lower]
    extra = [p for p in flat if p.lower() not in {w.lower() for w in want}]
    globals_ = [p for p in extra if p.lower() in GLOBAL_PINS]
    extra = [p for p in extra if p.lower() not in GLOBAL_PINS]
    if missing or extra:
        raise SystemExit(
            f"error: pins differ between {sym.name} and the extraction\n"
            f"  only in the symbol (no label in the layout?): {missing}\n"
            f"  only in the layout: {extra}\n"
            f"  (layout-only pins allowed: {', '.join(sorted(GLOBAL_PINS))}, tied to global GND)")

    # Magic's pins, in Magic's order, connect to the wrapper's (symbol-named) pins
    sym_name = {w.lower(): w for w in want}
    sym_name.update({p.lower(): GLOBAL_PINS[p.lower()] for p in globals_})
    md5 = hashlib.md5(gds.read_bytes()).hexdigest()
    out = HERE / f"{cell}_pex_wrapper.spice"
    out.write_text(
        f"* {cell}_pex: post-layout {cell} with the pin order of analog/neuron/{cell}.sym.\n"
        f"* GENERATED by make_pex_wrapper.py ({datetime.date.today()}); do not edit, re-run extract.sh.\n"
        f"* Extraction: {pex.name} (Magic, RC_extract.sh) of {gds.name}, md5 {md5}\n"
        f"* Magic's pin order: {' '.join(flat)}\n"
        + (f"* Layout-only pins tied to the global ground: {' '.join(globals_)}\n" if globals_ else "")
        + f".include {pex}\n\n"
        f".subckt {cell}_pex {' '.join(want)}\n"
        f"Xpex {' '.join(sym_name[p.lower()] for p in flat)} {cell}_flat\n"
        f".ends {cell}_pex\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
