"""Generate analog/snn/snn_analog.sch and .sym: the 2-2-1 network with signed synapses.

    python3 analog/snn/gen_snn_analog.py                  # separate DPI biases per layer (default)
    python3 analog/snn/gen_snn_analog.py --biases shared  # one DPI bias set (XOR fails, see README)

Neurons (as mock/snn_analog.v): 0, 1 = inputs; 2, 3 = hidden 0, 1; 4 = output.
Weight words (4 bits, sign-magnitude, w[4k+3:4k] = word k):
  0, 1          pulse[i] -> input i
  2 + 2j + i    input i  -> hidden j
  6 + j         hidden j -> output

Every synapse is a DAC_sm (1:2:4 magnitude from w[2:0], sign w[3]). Its excitatory current goes to
the tail of the neuron's DPI_sized; its inhibitory current to the tail of the neuron's DPI_inh,
which sinks from the membrane. The input neurons have no inhibitory DPI: their DAC_sm send an
inhibitory current to VDD, so a negative input weight gives no input at all (the mock clamps the
membrane at 0, which has the same effect).

Bias pins: shared mode uses one DPI bias pair (Vthr, VT_dpi) for every excitatory DPI and
(Vthr, VT_inh) for the inhibitory ones. Layer mode (the one in use, see
analog/testbenches/xor/README.md) gives the inputs Vthr_in / VT_in and the hidden layer
Vthr_hid / VT_hid, for its excitatory and inhibitory DPIs alike; the output keeps Vthr / VT_dpi,
and its inhibitory DPI uses Vthr / VT_inh.
"""

import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
CELLS = HERE.parent / "neuron"
HEAD = ["v {xschem version=3.4.8RC file_version=1.3}", "G {}", "K {}", "V {}", "S {}", "F {}", "E {}"]
NEURON_BIASES = ["VNA", "Vlk", "VK", "VIp", "VKup", "VKdn", "Vamp_bias", "VT"]
OLD_PINS = ["VDD", "VSS", "w[31:0]", "pulse[1:0]", "Vb", "Vthr", "VT_dpi"] + NEURON_BIASES


def pins(sym):
    """{pin name: (x, y)} of a symbol, from its pin boxes."""
    out = {}
    for m in re.finditer(r"^B 5 (\S+) (\S+) (\S+) (\S+) \{name=(\S+) dir=", (CELLS / f"{sym}.sym").read_text(), re.M):
        x1, y1, x2, y2 = map(float, m.groups()[:4])
        out[m.group(5)] = ((x1 + x2) / 2, (y1 + y2) / 2)
    return out


class Sch:
    def __init__(self):
        self.lines, self.n = list(HEAD), 0

    def inst(self, sym, x, y, name, conn):
        self.lines.append(f"C {{{sym}.sym}} {x} {y} 0 0 {{name={name}}}")
        p = pins(sym)
        assert set(conn) == set(p), (sym, set(p) ^ set(conn))
        for pin, net in conn.items():
            px, py = p[pin]
            self.n += 1
            self.lines.append(f"C {{lab_pin.sym}} {x + px:g} {y + py:g} 0 {1 if px > 0 else 0} "
                              f"{{name=l{self.n} sig_type=std_logic lab={net}}}")

    def text(self, s, x, y, size=0.4):
        self.lines.append(f"T {{{s}}} {x} {y} 0 0 {size} {size} {{}}")


def word(k):
    return f"w[{4 * k + 3}:{4 * k}]"


def build(mode):
    if mode == "shared":
        dpi_b = {"in": ("Vthr", "VT_dpi"), "hid": ("Vthr", "VT_dpi"), "out": ("Vthr", "VT_dpi")}
        new_pins = ["VT_inh"]
    else:
        dpi_b = {"in": ("Vthr_in", "VT_in"), "hid": ("Vthr_hid", "VT_hid"), "out": ("Vthr", "VT_dpi")}
        new_pins = ["VT_inh", "Vthr_in", "VT_in", "Vthr_hid", "VT_hid"]
    # inhibitory DPI biases: output: Vthr / VT_inh; hidden (layer mode): the layer's own pair, so that a
    # negative weight into a hidden neuron is as strong as a positive one
    inh_b = {"hid": ("Vthr", "VT_inh") if mode == "shared" else dpi_b["hid"], "out": ("Vthr", "VT_inh")}
    # neuron -> (layer, [(word, enable net)])
    net = {0: ("in", [(0, "pulse[0]")]), 1: ("in", [(1, "pulse[1]")]),
           2: ("hid", [(2, "spike[0]"), (3, "spike[1]")]), 3: ("hid", [(4, "spike[0]"), (5, "spike[1]")]),
           4: ("out", [(6, "spike[2]"), (7, "spike[3]")])}
    title = {0: "Input 0", 1: "Input 1", 2: "Hidden 0", 3: "Hidden 1", 4: "Output"}
    s = Sch()
    s.text(f"snn_analog: 2-2-1 network, signed synapses (generated by gen_snn_analog.py --biases {mode}).\n"
           "Synapse DACs are DAC_sm: w[4k+3] = sign (1 = inhibitory), w[4k+2:4k] = magnitude 0..7.\n"
           "Words: 0, 1 pulse -> input; 2 + 2j + i input i -> hidden j; 6 + j hidden j -> output.\n"
           "Excitatory DPIs are DPI_sized (x4 W and L); hidden and output neurons also have a DPI_inh.\n"
           "Inputs have no inhibitory DPI: their inhibitory DAC current goes to VDD.",
           -200, -1700, 0.3)
    for n, (layer, syn) in net.items():
        x, y = 400 + 700 * (n % 2 if n < 4 else 0), {0: -1300, 1: -1300, 2: -400, 3: -400, 4: 600}[n]
        s.text(title[n], x - 200, y - 140)
        isum, isumi, vmem = f"Isum_{n}", (f"Isumi_{n}" if layer != "in" else "VDD"), f"VMEM_{n}"
        for k, (wd, en) in enumerate(syn):
            s.inst("DAC_sm", x, y + 90 * k, f"xdac{n}_{k}",
                   {"Isum_e": isum, "w[3:0]": word(wd), "en": en, "Vb": "Vb", "Isum_i": isumi, "VDD": "VDD"})
        yd = y + 90 * len(syn) + 40
        vthr, vt = dpi_b[layer]
        s.inst("DPI_sized", x, yd, f"xdpi{n}", {"VDD": "VDD", "Vthr": vthr, "Isyn": vmem, "Isum": isum, "VT": vt})
        if layer != "in":
            yd += 80
            s.inst("DPI_inh", x, yd, f"xinh{n}", {"Vthr": inh_b[layer][0], "VT": inh_b[layer][1], "Isum": isumi,
                                                  "VDD": "VDD", "Iout": vmem})
        conn = {"VSS": "VSS", "VDD": "VDD", "VMEM": vmem, "spike": f"spike[{n}]"}
        conn.update({b: b for b in NEURON_BIASES})
        s.inst("neuron_sized", x, yd + 160, f"xneu{n}", conn)
    allpins = OLD_PINS + new_pins
    for i, p in enumerate(allpins):
        kind = "iopin" if p in ("VDD", "VSS") else "ipin"
        s.lines.append(f"C {{{kind}.sym}} -400 {-1300 + 30 * i} 0 0 {{name=p{i} lab={p}}}")
    s.lines.append(f"C {{opin.sym}} -300 {-1300 + 30 * len(allpins) + 30} 0 0 {{name=p{len(allpins)} lab=spike[4:0]}}")
    (HERE / "snn_analog.sch").write_text("\n".join(s.lines) + "\n")

    sym = ["v {xschem version=3.4.8RC file_version=1.3}", "G {}",
           'K {type=subcircuit\nformat="@name @pinlist @symname"\ntemplate="name=x1"\n}', "V {}", "S {}", "F {}", "E {}"]
    y0 = -140
    for i, p in enumerate(allpins):
        y = y0 + 20 * i
        d = "inout" if p in ("VDD", "VSS") else "in"
        sym += [f"L {7 if d == 'inout' else 4} -150 {y} -130 {y} {{}}",
                f"B 5 -152.5 {y - 2.5} -147.5 {y + 2.5} {{name={p} dir={d}}}", f"T {{{p}}} -125 {y - 4} 0 0 0.2 0.2 {{}}"]
    ybot = y0 + 20 * len(allpins)
    sym += ["L 4 130 0 150 0 {}", "B 5 147.5 -2.5 152.5 2.5 {name=spike[4:0] dir=out}",
            "T {spike[4:0]} 125 -4 0 1 0.2 0.2 {}",
            f"P 4 5 130 {y0 - 20} -130 {y0 - 20} -130 {ybot} 130 {ybot} 130 {y0 - 20} {{}}",
            "T {@symname} -40 -6 0 0 0.3 0.3 {}", f"T {{@name}} 135 {y0 - 32} 0 0 0.2 0.2 {{}}"]
    (HERE / "snn_analog.sym").write_text("\n".join(sym) + "\n")
    return allpins


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--biases", choices=["shared", "layer"], default="layer")
    print(" ".join(build(ap.parse_args().biases)))
